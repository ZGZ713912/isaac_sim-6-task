#!/usr/bin/env python3
"""Freeze the measured gas curve and V7 geometry for identical C++/Torch FF.

No policy, simulator or hardware is started. The right axial curve is the
user-authorized symmetry assumption; each side keeps its own signed geometry.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

from identify_gas_spring import geometry

ROOT = Path(__file__).resolve().parents[1]
RMCS = Path("/home/noir/Documents/workspace/RMCS")


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rmcs", type=Path, default=RMCS)
    args = parser.parse_args()
    source = ROOT / "model/gas_spring_identified_symmetric_20261028/model.json"
    bundle = ROOT / "model/纯底盘_v7_flat_base107/urdf"
    curve = json.loads(source.read_text())
    package = ROOT / "model/gas_spring_compensation_20261028"
    package.mkdir(parents=True, exist_ok=True)
    # Pad the geometry lookup beyond both configured active-difference soft
    # limits. Only the force law is extrapolated; geometry is solved anew.
    beta = np.linspace(39.5, 108.5, 277)
    compression = np.asarray(curve["compression_knots_m"])
    axial_force = np.asarray(curve["force_knots_n"])
    low_slope = (axial_force[1]-axial_force[0])/(compression[1]-compression[0])
    high_slope = (axial_force[-1]-axial_force[-2])/(compression[-1]-compression[-2])
    model = {"schema": "wheel-leg-gas-spring-compensation-v2", "version": 2,
        "coordinate": "active_model_output", "model_spec_sha256": digest(bundle / "model_spec.json"),
        "source_curve_sha256": digest(source), "source_curve": str(source),
        "measured_beta_domain_deg": curve["beta_domain_deg"],
        "geometry_beta_domain_deg": [float(beta[0]),float(beta[-1])],
        "soft_limit_active_difference_rad": [-.140638855,1.3889088544],
        "compression_knots_m": curve["compression_knots_m"], "force_knots_n": curve["force_knots_n"],
        "default_gain": 1.,
        "force_extension": {
            "low_compression": "F_low*exp(k_low*(s-s_low)); positive C1 extension",
            "low_compression_rate_per_m": float(low_slope/axial_force[0]),
            "high_compression": "F_high+k_high*(s-s_high); C1 linear endpoint trend",
            "high_compression_slope_n_per_m": float(high_slope),
            "scope": "unmeasured trend estimate; not independent identification"},
        "outside_geometry_domain": "zero compensation; physical simulation holds geometry-endpoint force",
        "coverage": "full configured active-difference soft-limit interval, no edge fade",
        "force_direction": "positive extension; holding torque=-dl/dq*F",
        "right_leg_symmetry_assumed": True, "direction_friction_compensated": False,
        "source_sha256": curve["source_sha256"], "sides": {}}
    for side in ("left", "right"):
        data = geometry(bundle, beta, side=side)
        names = data["names"].tolist()
        hip, aux = ("L_joint1", "LL_joint1") if side == "left" else ("R_joint1", "RR_joint1")
        h, a = data["poses"][:, names.index(hip)], data["poses"][:, names.index(aux)]
        delta = (a - h) * (1 if side == "left" else -1)
        if not np.all(np.diff(delta) > 0):
            raise ValueError("Nonmonotone active motor to passive knee mapping")
        model["sides"][side] = {"motor_names": [hip, aux], "delta_rad": delta.tolist(),
            "beta_deg": beta.tolist(), "compression_m": data["compression_m"].tolist(),
            "length_jacobian_m_per_rad": data["jacobian_m_per_rad"].tolist(),
            "closure_max_m": float(data["closure_m"].max())}
    content = json.dumps(model, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
    path = package / "model.json"
    path.write_text(content)
    model_sha = digest(path)
    header = ["// Generated by tools/export_gas_spring_compensation.py in isaac_wheeled_rl_train.",
        "// Model JSON SHA256: " + model_sha,
        "// RIGHT axial force uses the explicitly authorized LEFT symmetry assumption.",
        "#pragma once", "", "#include <array>", "#include <string_view>", "",
        "namespace rmcs_core::controller::chassis::gas_spring_model {", "",
        "inline constexpr std::string_view kModelSha256 = \"" + model_sha + "\";",
        "inline constexpr std::string_view kModelSpecSha256 = \"" + model["model_spec_sha256"] + "\";",
        "struct GeometryKnot {", "    double delta_rad, beta_deg, compression_m, hip_length_jacobian, knee_length_jacobian;", "};",
        "struct ForceKnot { double compression_m, force_n; };", ""]
    header.append(f"inline constexpr std::array<ForceKnot, {len(curve['force_knots_n'])}> kForce{{{{")
    header.extend(f"    {{{s:.17g}, {f:.17g}}}," for s, f in zip(curve["compression_knots_m"], curve["force_knots_n"]))
    header.extend(["}};", ""])
    header.extend([
        f"inline constexpr double kLowCompressionRate = {low_slope/axial_force[0]:.17g};",
        f"inline constexpr double kHighCompressionSlope = {high_slope:.17g};", ""])
    for side in ("left", "right"):
        row = model["sides"][side]
        header.append(f"inline constexpr std::array<GeometryKnot, {len(beta)}> k{side.capitalize()}{{{{")
        for d, b, s, j in zip(row["delta_rad"], row["beta_deg"], row["compression_m"], row["length_jacobian_m_per_rad"]):
            header.append("    {" + ", ".join(f"{v:.17g}" for v in (d, b, s, *j)) + "},")
        header.extend(["}};", ""])
    header.append("} // namespace rmcs_core::controller::chassis::gas_spring_model")
    target = args.rmcs / "rmcs_ws/src/rmcs_core/src/controller/chassis/wheel_leg/gas_spring_model.hpp"
    target.write_text("\n".join(header) + "\n")
    exported = args.rmcs / ".script/identification/calibration/gas_spring_compensation_20261028.json"
    exported.write_text(content)
    print(json.dumps({"model": str(path), "sha256": model_sha, "C++": str(target), "right_symmetry": True}), flush=True)


if __name__ == "__main__":
    main()

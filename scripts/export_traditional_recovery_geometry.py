#!/usr/bin/env python3
"""Export authenticated v202 geometry and spring compensation to the RMCS core.

This writes only the explicitly supplied isolated RMCS checkout. It neither
imports Isaac Sim nor starts any controller, learner, or hardware process.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0]=[str(ROOT/'src'),str(ROOT/'scripts'),str(ROOT/'tools')]


def export(rmcs):
    from wheeled_tasks.chassis.full_vehicle_training import authenticate
    plan=json.loads((ROOT/'contracts/wheel_leg_prone_motion_v4.json').read_text())
    cfg=json.loads((ROOT/plan['mechanism']['file']).read_text())
    authenticate(cfg,ROOT)
    geometry=json.loads((ROOT/'contracts/full_vehicle_recovery_geometry_v1.json').read_text())
    spring_cfg=cfg['v5_control']['gas_spring_compensation']
    spring_path=ROOT/spring_cfg['model_file']
    spring=json.loads(spring_path.read_text())
    if hashlib.sha256(spring_path.read_bytes()).hexdigest()!=spring_cfg['model_sha256']:
        raise ValueError('Spring source hash differs')
    import numpy as np
    from build_full_vehicle_training import ResetGeometry,geometry as kinematics
    from wheeled_tasks.chassis.side_fall_study import leg_configuration
    bundle=ROOT/cfg['asset_directory']; spec=json.loads((bundle/'model_spec.json').read_text())
    gravity_cache=ROOT/'contracts/full_vehicle_recovery_gravity_v1.json'
    if gravity_cache.exists() and json.loads(gravity_cache.read_text())['model_spec_sha256']==geometry['model_spec_sha256']:
        gravity_rows=json.loads(gravity_cache.read_text())['rows']
    else:
        builder=ResetGeometry(spec,bundle); gravity_rows=[]
        axes=['L_joint1','LL_joint1','R_joint1','RR_joint1']
        total=sum(b['mass'] for b in spec['bodies'])
        def quantity(q,side):
            frames=kinematics.fk(spec,q)
            moment=sum(b['mass']*kinematics.point(frames[b['name']],b['com']) for b in spec['bodies'])
            return moment-.5*total*frames[side+'_link3'][:3,3]
        for entry in geometry['rows']:
            q=leg_configuration(builder,(entry[0],)*2,(0.,0.));values=[entry[0]]
            for index,name in enumerate(axes):
                samples=[]
                for sign in (-1.,1.):
                    prescribed={n:q[n] for n in kinematics.ACTIVE};prescribed[name]+=sign*1e-4
                    moved=builder.solve(prescribed,q)
                    samples.append(quantity(moved,'L'if index<2 else'R'))
                values.extend(((samples[1]-samples[0])/2e-4).tolist())
            gravity_rows.append(values)
        gravity_cache.write_text(json.dumps(dict(schema='recovery-support-gravity/v1',
            model_spec_sha256=geometry['model_spec_sha256'],rows=gravity_rows,
            scope='CAD virtual work, half total weight per wheel; applied only during supported rise/capture'),indent=2)+'\n')
    lines=['#pragma once', '', '// Generated by export_traditional_recovery_geometry.py; do not hand edit.',
        '// Model SHA-256: '+geometry['model_spec_sha256'],
        '// Spring SHA-256: '+spring_cfg['model_sha256'],
        '#include "self_righting_core.hpp"', '',
        'namespace rmcs_core::controller::wheelleg::recovery_v202 {',
        'inline constexpr double stand_knee = '+repr(geometry['stand_knee_deg'])+';',
        'inline constexpr double stand_orbit = '+repr(geometry['stand_orbit_deg'])+';',
        'inline const std::vector<SelfRightingCore::Row> geometry = {']
    def row(values): return '    {'+', '.join(format(float(v),'.17g') for v in values)+'},'
    lines.extend(row(r) for r in geometry['rows']); lines+=['};','']
    for side in ('left','right'):
        s=spring['sides'][side]
        lines+=['inline constexpr std::array<std::array<double, 4>, '+str(len(s['delta_rad']))+'> '+side+' = {{']
        lines.extend(row((d,c,*j))for d,c,j in zip(s['delta_rad'],s['compression_m'],s['length_jacobian_m_per_rad']))
        lines+=['}};','']
    lines+=['inline constexpr std::array<std::array<double, 2>, '+str(len(spring['force_knots_n']))+'> force = {{']
    lines.extend(row(r) for r in zip(spring['compression_knots_m'],spring['force_knots_n']))
    low=spring['force_extension']['low_compression_rate_per_m']
    high=spring['force_extension']['high_compression_slope_n_per_m']
    lines+=['}};',r'''
template <std::size_t N, std::size_t M>
std::array<double, M> interpolate(const std::array<std::array<double, M>, N>& rows, double x) {
    x = std::clamp(x, rows.front()[0], rows.back()[0]);
    auto b = std::upper_bound(rows.begin(), rows.end(), x,
        [](double v, const auto& r) { return v < r[0]; });
    if (b == rows.end()) return rows.back();
    if (b == rows.begin()) return rows.front();
    const auto& a = *(b-1);
    const double t = (x-a[0])/((*b)[0]-a[0]);
    std::array<double, M> result{};
    for (std::size_t i=0; i<M; ++i) result[i]=a[i]+t*((*b)[i]-a[i]);
    return result;
}

inline SelfRightingCore::Axes compensation(const SelfRightingCore::Axes& q) {
    SelfRightingCore::Axes result{};
    for (std::size_t side=0; side<2; ++side) {
        const auto& rows=side==0 ? left : right;
        const double delta=side==0 ? q[1]-q[0] : q[2]-q[3];
        if (delta<rows.front()[0] || delta>rows.back()[0]) continue;
        const auto r=interpolate(rows,delta);
        double f=interpolate(force,r[1])[1];
''',
        f'        if (r[1]<force.front()[0]) f=force.front()[1]*std::exp({low:.17g}*(r[1]-force.front()[0]));',
        f'        if (r[1]>force.back()[0]) f=force.back()[1]+{high:.17g}*(r[1]-force.back()[0]);',
        f'        result[side*2]=-r[2]*f*{spring_cfg["gain"]:.17g};',
        f'        result[side*2+1]=-r[3]*f*{spring_cfg["gain"]:.17g};',
        '    }', '    return result;', '}', '',
        'inline constexpr std::array<std::array<double, 13>, '+str(len(gravity_rows))+'> support = {{']
    lines.extend(row(r) for r in gravity_rows)
    lines+=['}};',r'''
inline SelfRightingCore::Axes support_compensation(const SelfRightingCore::Axes& q,
        const std::array<double,3>& gravity) {
    SelfRightingCore::Axes effort{};
    for (std::size_t side=0; side<2; ++side) {
        const double delta=side==0 ? q[1]-q[0] : q[2]-q[3];
        double beta=geometry.back()[0];
        for (std::size_t i=1; i<geometry.size(); ++i) {
            const auto& a=geometry[i-1]; const auto& b=geometry[i];
            const double da=side==0 ? a[2]-a[1] : a[3]-a[4];
            const double db=side==0 ? b[2]-b[1] : b[3]-b[4];
            if (delta<=db) { beta=a[0]+std::clamp((delta-da)/(db-da),0.,1.)*(b[0]-a[0]); break; }
        }
        const auto coefficients=interpolate(support,beta);
        auto b=std::upper_bound(geometry.begin(),geometry.end(),beta,
            [](double v,const auto& r){return v<r[0];});
        if (b==geometry.end()) b=geometry.end()-1;
        if (b==geometry.begin()) ++b;
        const auto& a=*(b-1); const double t=(beta-a[0])/((*b)[0]-a[0]);
        const double zero=a[side*2+1]+t*((*b)[side*2+1]-a[side*2+1]);
        const double angle=(zero-q[side*2])*(side==0 ? 1. : -1.);
        for (std::size_t axis=side*2; axis<side*2+2; ++axis) {
            const double x=coefficients[1+axis*3],y=coefficients[2+axis*3],z=coefficients[3+axis*3];
            const double vx=std::cos(angle)*x-std::sin(angle)*z;
            const double vz=std::sin(angle)*x+std::cos(angle)*z;
            effort[axis]=-9.81*(gravity[0]*vx+gravity[1]*y+gravity[2]*vz);
        }
    }
    return effort;
}
''', '} // namespace rmcs_core::controller::wheelleg::recovery_v202', '']
    target=rmcs/'rmcs_ws/src/rmcs_core/src/controller/wheelleg/recovery_geometry_v202.hpp'
    target.write_text('\n'.join(lines))
    print(json.dumps(dict(file=str(target),sha256=hashlib.sha256(target.read_bytes()).hexdigest())))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rmcs',type=Path,required=True)
    export(parser.parse_args().rmcs.resolve())
